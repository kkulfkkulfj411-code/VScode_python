def get_trade_rules():
    return """
【トレード（エントリー・利益確定・撤退）の戦略基準】
スイングトレード（数日～数週間での決済）における買いエントリーは、以下の優先順位に従って選択してください。
※重要警告：リスクリワードを追求するあまり、「レンジの下限」や「長期支持線」など、「その価格まで落ちた時点ですでに短期的な上昇トレンドが崩壊（下降トレンド化）している」ような非現実的で深い押し目買い指値の提案は厳禁です。モメンタム（勢い）が維持される「浅い押し目」のみを狙ってください。

0. 【特例】現在値での即時エントリー（成行買い）
   分析時点の現在値がまさにブレイクアウト直後や、完璧な浅い押し目（反発確認直後）である場合、指値で待つ機会損失を避けるため「現在の価格で成行買い（または打診買い）」を提案してください。
1. 【最優先】ブレイク後のリテスト（サポレジ転換）での浅い押し目
   直近のレンジ上限や上値抵抗線を明確に上抜けたことを確認した後、かつての「抵抗線（レンジ上限）」が「支持線」へと転換して反発しようとする浅い戻り（押し目）ポイントでの買い指値。
2. 【第2優先】抵抗線上抜け（順張りブレイクアウト）
   直近の厚い上値抵抗線（レンジ上限）をまさに上抜けるタイミングを狙う「逆指値買い（ストップ買い）」。ボリンジャーバンドのスクイーズ等からモメンタム発生を伴うか確認してください。
3. 【第3優先】短期支持線反発の確認（コンフルエンス重視）
   短期的な上昇トレンドが継続している前提で、水平な支持線と短期動的サポート（25日SMA等）が重なる「コンフルエンス」地点での反発や、ダイバージェンス（逆行現象）を伴う反発の確認後のエントリー。
4. 【第4優先】支持線接近時の引き付け買い（※トレンド崩壊水準での指値は禁止）

決済基準（利益確定・損切り・停滞撤退）について：
・利益確定は次の上値抵抗線を基準とし、希望的観測を排除した現実的な価格に設定すること。
・【タイムストップ（停滞撤退）】：指値や目標価格に到達していなくても、「エントリー後〇日間、株価が横ばいでモメンタムが消失した場合は現在値で微益・微損撤退する」という時間軸ベースのエグジット基準を必ず提示してください。スイングトレードにおいて資金拘束の長期化はリスクとみなします。
・イベントリスク：決算発表や「TOPIX再編」等のイベントが控えている場合は、事実売りを回避するための期限を設けてください。
"""

